#!/usr/bin/env python3
"""Generate default full casing tables from pinned Unicode 17.0.0 UCD files."""
import argparse
import hashlib
from pathlib import Path

FILES = {
    'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
    'SpecialCasing.txt': 'efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588',
    'DerivedCoreProperties.txt': '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08',
}


def generate(source):
    data = {}
    for name, digest in FILES.items():
        raw = (source / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f'{name}: expected the pinned Unicode 17.0.0 file')
        data[name] = raw.decode('utf-8')
    upper, lower = {}, {}
    for line in data['UnicodeData.txt'].splitlines():
        fields = line.split(';')
        cp = int(fields[0], 16)
        for table, index in [(upper, 12), (lower, 13)]:
            if fields[index]:
                table[cp] = [int(fields[index], 16)]
    for line in data['SpecialCasing.txt'].splitlines():
        body = line.split('#', 1)[0].strip()
        if not body:
            continue
        fields = [f.strip() for f in body.split(';')]
        if fields[4]:
            # Final_Sigma is handled at runtime; locale tailoring is excluded.
            if fields[4] != 'Final_Sigma' and fields[4].split()[0] not in ('lt', 'tr', 'az'):
                raise ValueError(f'Unhandled special casing condition: {fields[4]}')
            continue
        cp = int(fields[0], 16)
        lower[cp] = [int(c, 16) for c in fields[1].split()]
        upper[cp] = [int(c, 16) for c in fields[3].split()]
    properties = {'Cased': [], 'Case_Ignorable': []}
    for line in data['DerivedCoreProperties.txt'].splitlines():
        body = line.split('#', 1)[0].strip()
        if not body:
            continue
        fields = [f.strip() for f in body.split(';')]
        if fields[1] in properties:
            bounds = fields[0].split('..')
            properties[fields[1]].append((int(bounds[0], 16), int(bounds[-1], 16)))
    out = ['/* Generated by tools/generate_unicode_case.py; do not edit.',
           ' * Unicode 17.0.0 data, copyright 2025 Unicode, Inc.',
           ' * Derived/modified tables; see third_party/unicode/LICENSE.txt (Unicode License V3).',
           ' */']
    for name, digest in FILES.items():
        out.append(f'/* SHA-256 {name}: {digest} */')
    for name, table in [('upper', upper), ('lower', lower)]:
        out.append(f'static const CaseMapping {name}_mappings[] = {{')
        for cp, mapping in sorted(table.items()):
            if mapping == [cp]:
                continue
            if not 1 <= len(mapping) <= 3:
                raise ValueError(f'Unsupported mapping length: {mapping}')
            padded = mapping + [0] * (3 - len(mapping))
            out.append(f'    {{0x{cp:X}, {{' + ', '.join(f'0x{c:X}' for c in padded) + f'}}, {len(mapping)}}},')
        out.append('};')
    for name, ranges in properties.items():
        merged = []
        for start, end in sorted(ranges):
            if merged and start <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
            else:
                merged.append((start, end))
        out.append(f'static const CodeRange {name.lower()}_ranges[] = {{')
        out.extend(f'    {{0x{start:X}, 0x{end:X}}},' for start, end in merged)
        out.append('};')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ucd_dir', type=Path)
    parser.add_argument('--output', type=Path, default=Path('src/unicode_case_data.inc'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate(args.ucd_dir)
    if args.check:
        if args.output.read_text() != generated:
            raise SystemExit(f'{args.output}: regenerate Unicode case tables')
    else:
        args.output.write_text(generated)
